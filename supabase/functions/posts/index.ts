/// Marker line prefixes that carry structured metadata, not
/// user-visible text.  Excluded from the visible-caption length check
/// so a music post with linked videos, lyrics, liner notes, release
/// date, etc. doesn't blow past the 220-char limit on a long marker
/// payload that the user never sees.  Plain photo/video/text posts
/// can also embed the carousel + collaborator markers, so those are
/// stripped from any caption shape.
const STRUCTURED_CAPTION_MARKER_PREFIXES = [
  "[AUDIO_LOOP_VIDEO]",
  "[MUSIC_LOOP_VIDEO]",
  "[MUSIC_RELEASE_TYPE]",
  "[MUSIC_TRACKS_BASE64]",
  "[MUSIC_RELEASE_DATE]",
  "[MUSIC_RECORD_LABEL]",
  "[MUSIC_LINER_NOTES_BASE64]",
  "[MUSIC_VIDEO_LINKS_BASE64]",
  "[PHOTO_CAROUSEL_BASE64]",
  "[SCROLL_COLLABORATORS_BASE64]",
];

function stripStructuredMarkerLines(body: string): string {
  return body
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => {
      if (line.length === 0) return false;
      const upper = line.toUpperCase();
      for (const prefix of STRUCTURED_CAPTION_MARKER_PREFIXES) {
        if (upper.startsWith(prefix)) return false;
      }
      return true;
    })
    .join("\n")
    .trim();
}

function visibleCaptionForValidation(rawCaption: string): string {
  const trimmed = rawCaption.trim();
  if (!trimmed) return "";

  const extractStructuredAudioDisplayCaption = (prefix: string): string => {
    const remainder = trimmed.slice(prefix.length).trim();
    if (!remainder) return "";
    return stripStructuredMarkerLines(remainder);
  };

  const upper = trimmed.toUpperCase();
  if (upper.startsWith("[PODCAST]")) {
    return extractStructuredAudioDisplayCaption("[PODCAST]");
  }
  if (upper.startsWith("[MUSIC]")) {
    return extractStructuredAudioDisplayCaption("[MUSIC]");
  }
  if (upper.startsWith("[ARTICLE]")) {
    return trimmed.slice("[ARTICLE]".length).trim();
  }
  // Plain captions (photo / video / text posts) can also carry the
  // carousel and collaborator markers — strip those too before the
  // length count so adding 1-4 collaborators or a 4-photo carousel
  // doesn't trip the 220-char limit.
  return stripStructuredMarkerLines(trimmed);
}

/// Pull the list of collaborator UUIDs the iOS client packed into the
/// caption under the `[SCROLL_COLLABORATORS_BASE64]` marker.  Mirrors
/// `FeedPost.scrollCollaboratorIDs` in ScrollsModels.swift.  Returns an
/// empty array on any decoding failure so callers can treat the absence
/// of a marker and a malformed marker the same way.
function collaboratorIDsFromCaption(rawCaption: unknown): string[] {
  const trimmed = String(rawCaption ?? "").trim();
  if (!trimmed) return [];
  const marker = "[SCROLL_COLLABORATORS_BASE64]";
  for (const rawLine of trimmed.split(/\r?\n/)) {
    const line = rawLine.trim();
    if (!line) continue;
    if (!line.toUpperCase().startsWith(marker)) continue;
    const suffix = line.slice(marker.length).trim();
    if (!suffix) return [];
    try {
      const decoded = atob(suffix);
      const parsed = JSON.parse(decoded);
      if (!Array.isArray(parsed)) return [];
      const ids: string[] = [];
      for (const entry of parsed) {
        const id = String(entry ?? "").trim().toLowerCase();
        // Light UUID shape check — backend RLS / FK constraints will
        // reject anything that isn't a real user_id anyway, but skipping
        // obvious junk here saves a round-trip.
        if (/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/.test(id)) {
          ids.push(id);
        }
      }
      return ids;
    } catch {
      return [];
    }
  }
  return [];
}

/// Insert one notification row per tagged collaborator (excluding the
/// post author themselves) and fire an APNs push for each.  Best-effort:
/// any DB / push failures are logged but never surfaced to the caller,
/// since the post is already persisted at this point.
async function notifyCollaborators(
  admin: ReturnType<typeof serviceClient>,
  postID: string,
  authorID: string,
  caption: unknown,
): Promise<void> {
  const ids = collaboratorIDsFromCaption(caption);
  if (ids.length === 0) return;
  const authorIDNormalized = String(authorID ?? "").trim().toLowerCase();
  // Dedupe + drop the author so we never notify someone for tagging
  // themselves (the iOS picker already filters this, but defense in
  // depth keeps a malformed payload from spamming the author).
  const recipients = Array.from(new Set(ids)).filter((id) => id && id !== authorIDNormalized);
  if (recipients.length === 0) return;

  // Only notify users that actually exist — a stale UUID from a deleted
  // account shouldn't create an orphan notification row.
  const lookup = await admin.from("users").select("id").in("id", recipients);
  if (lookup.error) {
    console.error(JSON.stringify({
      event:   "collaborator_lookup_error",
      post_id: postID,
      error:   lookup.error.message,
    }));
    return;
  }
  const validRecipients = (lookup.data ?? [])
    .map((row) => String((row as { id?: unknown }).id ?? "").trim().toLowerCase())
    .filter(Boolean);
  if (validRecipients.length === 0) return;

  const actorUsername = await usernameForUserID(admin, authorIDNormalized);
  const nowISO = new Date().toISOString();
  const rows = validRecipients.map((recipient) => ({
    user_id:    recipient,
    type:       "collaborated",
    actor_id:   authorIDNormalized,
    object_id:  postID,
    title:      actorUsername ? `Tagged by @${actorUsername}` : "You were tagged",
    message:    actorUsername
      ? `@${actorUsername} tagged you as a collaborator on their scroll.`
      : "You were tagged as a collaborator on a scroll.",
    is_read:    false,
    created_at: nowISO,
  }));

  const insert = await admin.from("notifications").insert(rows);
  if (insert.error) {
    console.error(JSON.stringify({
      event:   "collaborator_notification_insert_error",
      post_id: postID,
      error:   insert.error.message,
    }));
    // Still try the push fanout — even without an in-app row, the user
    // should learn they were tagged.
  }

  const pushBody = actorUsername
    ? `@${actorUsername} tagged you as a collaborator on their scroll.`
    : "You were tagged as a collaborator on a scroll.";
  await Promise.allSettled(
    validRecipients.map((recipient) =>
      sendPushToUser(admin, recipient, {
        title:    "Tagged on a scroll",
        body:     pushBody,
        threadId: `scroll-${postID}`,
        custom:   { scroll_url: `scrolls://scroll/${postID}` },
      })
    ),
  );
}

function looksLikeMusicAudioObjectKey(objectKey: unknown): boolean {
  const raw = String(objectKey ?? "").trim().toLowerCase().split("?")[0];
  if (!raw) return false;
  return raw.endsWith(".aac") || raw.endsWith(".m4a") || raw.endsWith(".wav");
}

function looksLikeVideoObjectKey(objectKey: unknown): boolean {
  const raw = String(objectKey ?? "").trim().toLowerCase().split("?")[0];
  if (!raw) return false;
  return raw.endsWith(".mp4") || raw.endsWith(".mov") || raw.endsWith(".m4v") || raw.endsWith(".webm");
}


async function userHasFounderAccess(admin: ReturnType<typeof serviceClient>, userIDRaw: string): Promise<boolean> {
  const userID = String(userIDRaw ?? "").trim().toLowerCase();
  if (!userID) return false;
  if (isFounderUserID(userID)) return true;
  const row = await admin.from("users").select("is_founder").eq("id", userID).maybeSingle();
  if (row.error) return false;
  return Boolean(row.data?.is_founder ?? false);
}

