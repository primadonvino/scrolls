async function createPost(req: Request, authed: string) {
  const payload = await req.json();
  const postID = String(payload.id ?? "").trim();
  const requestedAuthorID = String(payload.authorID ?? "");
  const authorID = await resolveAuthorIDForWrite(authed, requestedAuthorID);
  if (!postID) return badRequest("Post ID required.");
  if (!authorID) return unauthorized();

  const caption = String(payload.caption ?? "");
  const textBody = String(payload.textBody ?? "");
  if (containsBlockedAIText(caption) || containsBlockedAIText(textBody)) {
    return badRequest("AI-generated content is not allowed.");
  }
  if (containsBlockedNudityText(caption) || containsBlockedNudityText(textBody)) {
    return badRequest("Explicit nudity content is not allowed.");
  }

  const assetWrite = await resolveMediaWriteFromPayload(payload, {
    kind: "asset",
    authed,
    authorID,
    postID,
    requireReference: false,
    allowStreamProvider: true,
  });
  if ("error" in assetWrite) return assetWrite.error;

  const coverWrite = await resolveMediaWriteFromPayload(payload, {
    kind: "cover",
    authed,
    authorID,
    postID,
    requireReference: false,
    allowStreamProvider: false,
  });
  if ("error" in coverWrite) return coverWrite.error;

if (isPodcastCaption(payload.caption) && looksLikeVideoObjectKey(assetWrite.value.objectKey)) {
  return badRequest("Podcasts are audio-only on Scrolls.");
}

const admin = serviceClient();
if (isMusicCaption(payload.caption)) {
  if (!looksLikeMusicAudioObjectKey(assetWrite.value.objectKey)) {
    return badRequest("Music uploads must be AAC, M4A, or Apollo-bounced WAV audio.");
  }
  const allowanceError = await validateMusicUploadAllowance(admin, authorID, payload.caption);
  if (allowanceError) return allowanceError;
}

  const existing = await admin.from("posts")
    .select("id, author_id, caption, created_at")
    .eq("id", postID)
    .maybeSingle();
  if (existing.error) return badRequest(existing.error.message);
  if (existing.data) {
    if (String(existing.data.author_id ?? "") !== authorID) {
      return badRequest("Post ID conflict.");
    }
    const existingCreatedAt = normalizeCreatedAt(existing.data.created_at);
    // Fanout is best-effort: post is already created, so never fail the
    // response over a feed-distribution error.
    try {
      await fanoutPostToFollowerTimelines(admin, authorID, postID, existingCreatedAt);
    } catch (fanoutError) {
      console.error(JSON.stringify({ event: "post_fanout_error_idempotent", post_id: postID, error: String(fanoutError) }));
    }
    return json({ ok: true, idempotent: true, id: postID });
  }

  const createdAt = normalizeCreatedAt(payload.createdAt);
  const subscriptionUnlockedAt = await subscriptionUnlockedTimestampForAuthor(admin, authorID, payload.caption);
  const write = await admin.from("posts").insert({
    id: postID,
    author_id: authorID,
    type: String(payload.type),
    caption: payload.caption ?? null,
    website_url: payload.websiteURL ?? null,
    location_city: payload.locationCity ?? null,
    text_body: payload.textBody ?? null,
    asset_ref: null,
    asset_provider: assetWrite.value.provider,
    asset_bucket: assetWrite.value.bucket,
    asset_object_key: assetWrite.value.objectKey,
    cover_image_ref: null,
    cover_provider: coverWrite.value.provider,
    cover_bucket: coverWrite.value.bucket,
    cover_object_key: coverWrite.value.objectKey,
    aspect_ratio: payload.aspectRatio ?? null,
    created_at: createdAt,
    updated_at: new Date().toISOString(),
    subscription_unlocked_at: subscriptionUnlockedAt,
  });
  if (write.error) return badRequest(write.error.message);
  // Fanout is best-effort: post is already persisted, so never surface a
  // feed-distribution error to the user.
  try {
    await fanoutPostToFollowerTimelines(admin, authorID, postID, createdAt);
  } catch (fanoutError) {
    console.error(JSON.stringify({ event: "post_fanout_error", post_id: postID, error: String(fanoutError) }));
  }
  // Collaborator notifications are best-effort as well: any DB or APNs
  // failure shouldn't fail the post creation, since the row is durable.
  try {
    await notifyCollaborators(admin, postID, authorID, payload.caption);
  } catch (collabError) {
    console.error(JSON.stringify({ event: "collaborator_notification_error", post_id: postID, error: String(collabError) }));
  }
  return json({ ok: true, id: postID });
}
function normalizeCreatedAt(value: unknown): string {
  if (typeof value === "string" && value.trim()) {
    const parsed = new Date(value);
    if (!Number.isNaN(parsed.getTime())) return parsed.toISOString();
  }
  if (typeof value === "number" && Number.isFinite(value)) {
    let seconds = value;
    if (Math.abs(seconds) > 1_000_000_000_000) {
      // Defensive support for millisecond epochs.
      seconds = seconds / 1000;
    }
    if (seconds > 0 && seconds < 1_200_000_000) {
      // Swift JSONEncoder default date strategy sends seconds since Apple's reference date (2001-01-01).
      const appleReferenceEpochSeconds = Date.UTC(2001, 0, 1) / 1000;
      return new Date((seconds + appleReferenceEpochSeconds) * 1000).toISOString();
    }
    return new Date(seconds * 1000).toISOString();
  }
  return new Date().toISOString();
}

async function uploadMedia(req: Request, authed: string) {
  const contentTypeHeader = (req.headers.get("content-type") ?? "").toLowerCase();
  const url = new URL(req.url);
  const payload = contentTypeHeader.includes("application/json")
    ? await req.json()
    : null;

  const requestedAuthorID = String(
    payload?.authorID ??
      url.searchParams.get("authorID") ??
      req.headers.get("x-scrolls-author-id") ??
      "",
  ).trim();
  const authorID = await resolveAuthorIDForWrite(authed, requestedAuthorID);
  if (!authorID) return unauthorized();

  const postID = String(
    payload?.postID ??
      url.searchParams.get("postID") ??
      req.headers.get("x-scrolls-post-id") ??
      "",
  ).trim();
  if (!postID) return badRequest("postID is required.");

  const kind = String(
    payload?.type ??
      url.searchParams.get("type") ??
      req.headers.get("x-scrolls-media-type") ??
      "",
  ).toLowerCase();
  if (kind !== "photo" && kind !== "video") {
    return badRequest("Unsupported media type.");
  }

  const fileName = String(
    payload?.fileName ??
      url.searchParams.get("fileName") ??
      req.headers.get("x-scrolls-file-name") ??
      "",
  ).trim();
  if (!fileName) return badRequest("fileName is required.");

  let binary: Uint8Array;
  if (payload) {
    const dataBase64 = String(payload.dataBase64 ?? "");
    if (!dataBase64) return badRequest("dataBase64 is required.");
    try {
      binary = Uint8Array.from(atob(dataBase64), (char) => char.charCodeAt(0));
    } catch {
      return badRequest("Invalid base64 payload.");
    }
  } else {
    try {
      binary = new Uint8Array(await req.arrayBuffer());
    } catch {
      return badRequest("Could not read media payload.");
    }
  }

  if (binary.byteLength === 0) return badRequest("Uploaded media is empty.");

  const admin = serviceClient();
  const userRow = await admin.from("users").select("is_founder").eq("id", authorID).maybeSingle();
  if (userRow.error) return badRequest(userRow.error.message);
  const isFounder = Boolean(userRow.data?.is_founder ?? false);

  if (!isFounder && binary.byteLength > 50 * 1024 * 1024) {
    return badRequest("Uploaded media is too large.");
  }

  const extension = fileName.includes(".") ? fileName.split(".").pop()!.toLowerCase() : "";
  const contentType =
    kind === "photo"
      ? (extension === "png" ? "image/png" : "image/jpeg")
      : (extension === "mov" ? "video/quicktime" : "video/mp4");

  const storagePath = `${authorID}/${postID}/${kind}-${Date.now()}.${extension || (kind === "photo" ? "jpg" : "mp4")}`;
  const bucket = isFounder ? "founder-post-media" : "post-media";
  const upload = await admin.storage
    .from(bucket)
    .upload(storagePath, binary, {
      upsert: true,
      contentType,
      cacheControl: "31536000",
    });
  if (upload.error) return badRequest(upload.error.message);

  const publicURL = admin.storage.from(bucket).getPublicUrl(storagePath).data.publicUrl;
  if (!publicURL) return badRequest("Failed to build media URL.");
  return json({ assetRef: publicURL });
}

