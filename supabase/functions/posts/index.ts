async function resolveAuthorIDForWrite(authedRaw: string, requestedRaw: string): Promise<string | null> {
  const authed = String(authedRaw ?? "").trim().toLowerCase();
  const requested = String(requestedRaw ?? "").trim().toLowerCase();
  if (!authed) return null;
  if (requested && await canActAsAccount(authed, requested)) {
    return requested;
  }
  // Fallback to authenticated account to avoid stale client account-ID windows causing
  // hard publish failures; this preserves security by never allowing cross-account spoofing.
  return authed;
}

