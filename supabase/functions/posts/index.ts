async function deletePost(req: Request, authed: string) {
  const payload = await req.json();
  const requestedAuthorID = String(payload.authorID ?? "").trim().toLowerCase();
  const postID = String(payload.postID ?? "");
  const admin = serviceClient();
  const founderOverride = await userHasFounderAccess(admin, authed);

  const existing = await admin.from("posts")
    .select("author_id, asset_ref, asset_provider, asset_bucket, asset_object_key, cover_image_ref, cover_provider, cover_bucket, cover_object_key, caption")
    .eq("id", postID)
    .maybeSingle();
  if (existing.error) return badRequest(existing.error.message);

  const actualAuthorID = existing.data
    ? String((existing.data as Record<string, unknown>).author_id ?? "").trim().toLowerCase()
    : requestedAuthorID;
  const canDeleteRequestedAuthor = requestedAuthorID ? await canActAsAccount(authed, requestedAuthorID) : false;
  const canDeleteActualAuthor = actualAuthorID ? await canActAsAccount(authed, actualAuthorID) : false;
  if (!founderOverride && !canDeleteRequestedAuthor && !canDeleteActualAuthor) return unauthorized();

  const writeDeletionTombstone = async () => {
    const tombstoneWrite = await admin.from("deleted_post_tombstones").upsert({
      post_id: postID,
      author_id: actualAuthorID || requestedAuthorID,
      deleted_at: new Date().toISOString(),
    }, { onConflict: "post_id" });
    if (tombstoneWrite.error) return badRequest(tombstoneWrite.error.message);
    return null;
  };

  if (!existing.data) {
    // The row may already be gone, but stale clients still need a fresh purge
    // signal. Re-upsert the tombstone and clear any dangling feed/rescroll rows
    // so "delete again" still repairs old caches across devices.
    const tombstoneError = await writeDeletionTombstone();
    if (tombstoneError) return tombstoneError;
    await admin.from("rescrolls").delete().eq("original_post_id", postID);
    await admin.from("user_feed_items").delete().eq("post_id", postID);
    return json({ ok: true });
  }

  // CRITICAL ORDERING: write the tombstone and hard-delete the row BEFORE any
  // storage purging. Music posts can carry many files (album cover + several
  // audio tracks across two buckets and two folder prefix conventions), and the
  // storage list+remove loop can be slow enough to exhaust the edge function
  // wall-clock. If we purge first and time out, the row stays visible on
  // followers' feeds and in search forever. Tombstone-first guarantees that a
  // partial run still hides the post everywhere; the storage sweep is then a
  // best-effort cleanup that can be retried safely (the row is already gone).
  const legacyRefs = collectLegacyRefs(
    existing.data.asset_ref,
    existing.data.cover_image_ref,
    ...parseMusicTrackMetadata(typeof existing.data.caption === "string" ? existing.data.caption : null)
      .map((track) => track.audioURL)
      .filter((value): value is string => typeof value === "string" && value.trim().length > 0),
  );
  const structuredRefs = [
    ...collectStructuredRefs(existing.data.asset_provider, existing.data.asset_bucket, existing.data.asset_object_key),
    ...collectStructuredRefs(existing.data.cover_provider, existing.data.cover_bucket, existing.data.cover_object_key),
  ];

  // 1. Tombstone first — instantly hides the post from search and feeds even if
  //    everything downstream times out.
  const tombstoneError = await writeDeletionTombstone();
  if (tombstoneError) return tombstoneError;

  // 2. Hard-delete the posts row. Cascade FKs handle post_likes, comments,
  //    rescrolls, post_reports, ad_review_queue, and user_feed_items
  //    automatically, but we still explicitly clear rescrolls/user_feed_items
  //    below as a belt-and-suspenders measure against any rows whose cascade
  //    triggers are disabled in this environment.
  const deleted = await admin.from("posts")
    .delete()
    .eq("id", postID);
  if (deleted.error) return badRequest(deleted.error.message);

  const rescrollDelete = await admin.from("rescrolls")
    .delete()
    .eq("original_post_id", postID);
  if (rescrollDelete.error) {
    // The row is already gone and the tombstone is in place — don't bubble this
    // up as a hard failure. Log and continue so the client doesn't endlessly
    // retry a delete that has effectively succeeded.
    console.warn(JSON.stringify({
      event: "delete_post_rescroll_purge_failed",
      post_id: postID,
      message: rescrollDelete.error.message,
    }));
  }

  const feedItemDelete = await admin.from("user_feed_items")
    .delete()
    .eq("post_id", postID);
  if (feedItemDelete.error) {
    console.warn(JSON.stringify({
      event: "delete_post_feed_item_purge_failed",
      post_id: postID,
      message: feedItemDelete.error.message,
    }));
  }

  // 3. Best-effort storage purge LAST. If we time out here, the post is
  //    already invisible everywhere; the iOS client's retry will hit the
  //    !existing.data branch above and re-attempt the tombstone — orphan
  //    storage objects get reclaimed by the storage-orphan-sweep cron.
  try {
    const legacyFolderPrefix = `${actualAuthorID}/${postID}`;
    const typedFolderPrefix = `posts/${actualAuthorID}/${postID}`;
    const bucketsToCheck = ["post-media", "founder-post-media"];
    for (const bucket of bucketsToCheck) {
      for (const prefix of [legacyFolderPrefix, typedFolderPrefix]) {
        const listed = await admin.storage.from(bucket).list(prefix, { limit: 200 });
        if (!listed.error && listed.data && listed.data.length > 0) {
          const paths = listed.data.map((f) => `${prefix}/${f.name}`);
          // Remove in batches of 50 to stay within API limits.
          for (let i = 0; i < paths.length; i += 50) {
            await admin.storage.from(bucket).remove(paths.slice(i, i + 50));
          }
        }
      }
    }
    await quarantineDeletedPostStorageRefs(admin, legacyRefs, structuredRefs, {
      postID,
      authorID: actualAuthorID || requestedAuthorID,
    });
  } catch (storageError) {
    console.warn(JSON.stringify({
      event: "delete_post_storage_purge_failed",
      post_id: postID,
      message: storageError instanceof Error ? storageError.message : String(storageError),
    }));
  }

  return json({ ok: true });
}

async function reportPost(req: Request, authed: string) {
  const payload = await req.json();
  const postID = String(payload.postID ?? "").trim();
  const reason = String(payload.reason ?? "").trim().toLowerCase();
  const notes = String(payload.notes ?? "").trim();
  if (!postID) return badRequest("postID is required.");
  if (![
    "drugs",
    "violence",
    "nudity_sexual_themes",
    "spam",
    "harassment_bullying",
    "hate_speech_discrimination",
    "misinformation",
    "copyright_violation",
    "impersonation",
  ].includes(reason)) {
    return badRequest("Invalid report reason.");
  }

  const admin = serviceClient();
  const blocked = await isReporterTemporarilyBlocked(admin, authed);
  if (blocked) {
    return badRequest("Reporting is temporarily limited due to high false-report activity.");
  }
  const rateLimited = await isReporterRateLimited(admin, authed);
  if (rateLimited) {
    return badRequest("You've reached the report limit. Please try again later.");
  }

  const post = await admin.from("posts").select("id, author_id, caption").eq("id", postID).is("deleted_at", null).maybeSingle();
  if (post.error) return badRequest(post.error.message);
  if (!post.data) return badRequest("Post not found.");
  if (String(post.data.author_id) === authed) return badRequest("Cannot report your own post.");

  const write = await admin.from("post_reports").upsert({
    post_id: postID,
    reporter_id: authed,
    reason,
    notes: notes || null,
    status: "pending",
    reviewed_by: null,
    reviewed_at: null,
    updated_at: new Date().toISOString(),
  }, { onConflict: "post_id,reporter_id" });
  if (write.error) return badRequest(write.error.message);

  await syncPostReportCount(admin, postID);
  return json({ ok: true });
}

async function isReporterRateLimited(admin: ReturnType<typeof serviceClient>, reporterID: string): Promise<boolean> {
  const cutoffISO = new Date(Date.now() - (REPORT_RATE_LIMIT_WINDOW_HOURS * 60 * 60 * 1000)).toISOString();
  const recent = await admin.from("post_reports")
    .select("id", { count: "exact", head: true })
    .eq("reporter_id", reporterID)
    .gte("created_at", cutoffISO);
  if (recent.error) return false;
  return Number(recent.count ?? 0) >= REPORT_RATE_LIMIT_MAX;
}

async function isReporterTemporarilyBlocked(admin: ReturnType<typeof serviceClient>, reporterID: string): Promise<boolean> {
  const cutoffISO = new Date(Date.now() - (REPORT_TRUST_WINDOW_DAYS * 24 * 60 * 60 * 1000)).toISOString();
  const reviewed = await admin.from("post_reports")
    .select("status")
    .eq("reporter_id", reporterID)
    .in("status", ["confirmed", "dismissed"])
    .gte("updated_at", cutoffISO);
  if (reviewed.error) return false;
  const rows = reviewed.data ?? [];
  if (rows.length < REPORT_TRUST_MIN_REVIEWED) return false;
  const dismissed = rows.filter((row) => String(row.status) === "dismissed").length;
  const dismissRatio = dismissed / rows.length;
  return dismissRatio >= REPORT_TRUST_MAX_DISMISS_RATIO;
}

