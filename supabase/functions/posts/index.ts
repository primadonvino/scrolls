async function updateCaption(req: Request, authed: string) {
  const payload = await req.json();
  const postID = String(payload.postID ?? "").trim();
  const requestedAuthorID = String(payload.authorID ?? "").trim();
  if (!postID) return badRequest("postID required.");

  const authorID = await resolveAuthorIDForWrite(authed, requestedAuthorID);
  if (!authorID) return unauthorized();

  // Apply the same content-moderation rules as post creation.
  const newCaption = "caption" in payload
    ? (typeof payload.caption === "string" ? payload.caption.trim() : null)
    : undefined;
  if (typeof newCaption === "string" && newCaption.length > 0) {
    const visibleCaption = visibleCaptionForValidation(newCaption);
    if (containsBlockedAIText(newCaption)) return badRequest("AI-generated content is not allowed.");
    if (containsBlockedNudityText(newCaption)) return badRequest("Explicit nudity content is not allowed.");
    if (visibleCaption.length > 220) return badRequest("Caption too long.");
  }

  const admin = serviceClient();
  const existing = await admin.from("posts")
    .select("id, author_id, caption, asset_object_key, subscription_unlocked_at")
    .eq("id", postID)
    .eq("author_id", authorID)
    .is("deleted_at", null)
    .maybeSingle();
  if (existing.error) return badRequest(existing.error.message);
  if (!existing.data) return unauthorized();

  if (typeof newCaption === "string" && isPodcastCaption(newCaption) && looksLikeVideoObjectKey(existing.data.asset_object_key)) {
    return badRequest("Podcasts are audio-only on Scrolls.");
  }
  if (typeof newCaption === "string" && isMusicCaption(newCaption)) {
    if (!looksLikeMusicAudioObjectKey(existing.data.asset_object_key)) {
      return badRequest("Music uploads must be AAC, M4A, or Apollo-bounced WAV audio.");
    }
    const allowanceError = await validateMusicUploadAllowance(admin, authorID, newCaption, postID);
    if (allowanceError) return allowanceError;
  }

  const update: Record<string, unknown> = { updated_at: new Date().toISOString() };
  if (typeof newCaption !== "undefined") {
    update.caption = (typeof newCaption === "string" && newCaption.length > 0) ? newCaption : null;
    update.subscription_unlocked_at = isSubscriptionUnlockedCaption(newCaption)
      ? (existing.data.subscription_unlocked_at ?? await subscriptionUnlockedTimestampForAuthor(admin, authorID, newCaption))
      : null;
  }
  if ("locationCity" in payload) {
    const city = typeof payload.locationCity === "string" ? payload.locationCity.trim() : null;
    update.location_city = city && city.length > 0 ? city : null;
  }

  const write = await admin.from("posts").update(update).eq("id", postID).eq("author_id", authorID);
  if (write.error) return badRequest(write.error.message);

  if (typeof newCaption === "string" && isMusicCaption(newCaption)) {
    const oldMusicTracks = parseMusicTrackMetadata(existing.data.caption);
    const newMusicTracks = parseMusicTrackMetadata(newCaption);
    await removeReplacedStorageRefsIfNeeded(
      admin,
      oldMusicTracks.map((t) => t.audioURL).filter((u): u is string => u !== null),
      [],
      newMusicTracks.map((t) => t.audioURL).filter((u): u is string => u !== null),
      [],
    );
  }

  // Notify any collaborators added by this edit (diff against the old
  // caption so re-saves don't re-spam users who were tagged earlier).
  if (typeof newCaption === "string") {
    try {
      const previous = new Set(collaboratorIDsFromCaption(existing.data.caption));
      const updated = collaboratorIDsFromCaption(newCaption);
      const added = updated.filter((id) => !previous.has(id));
      if (added.length > 0) {
        // Re-encode just the additions into a stripped marker string so
        // notifyCollaborators can reuse its existing decoder path.
        const markerPayload = btoa(JSON.stringify(added));
        await notifyCollaborators(
          admin,
          postID,
          authorID,
          `[SCROLL_COLLABORATORS_BASE64] ${markerPayload}`,
        );
      }
    } catch (collabError) {
      console.error(JSON.stringify({
        event:   "collaborator_notification_edit_error",
        post_id: postID,
        error:   String(collabError),
      }));
    }
  }

  return json({ ok: true });
}

type StructuredStorageRef = {
  provider: "supabase" | "r2";
  bucket: string;
  objectKey: string;
};

type MusicTrackCaptionMetadata = {
  title: string;
  audioURL: string | null;
};

function parseMusicTrackMetadata(caption: string | null): MusicTrackCaptionMetadata[] {
  const raw = typeof caption === "string" ? caption.trim() : "";
  if (!raw) return [];
  const upper = raw.toUpperCase();
  if (!upper.startsWith("[MUSIC]")) return [];
  const lines = raw
    .split(/\r?\n/)
    .map((line) => line.trim())
    .filter((line) => line.length > 0);
  const prefix = "[MUSIC_TRACKS_BASE64]";
  for (const line of lines) {
    if (!line.toUpperCase().startsWith(prefix)) continue;
    const encoded = line.slice(prefix.length).trim();
    if (!encoded) return [];
    try {
      const decoded = JSON.parse(new TextDecoder().decode(Uint8Array.from(atob(encoded), (char) => char.charCodeAt(0)))) as Array<Record<string, unknown>>;
      return decoded.map((item) => ({
        title: typeof item.title === "string" ? item.title : "",
        audioURL: typeof item.audioURL === "string" && item.audioURL.trim().length > 0 ? item.audioURL.trim() : null,
      }));
    } catch {
      return [];
    }
  }
  return [];
}

function collectLegacyRefs(...refs: Array<string | null | undefined>): string[] {
  return refs
    .map((ref) => typeof ref === "string" ? ref.trim() : "")
    .filter((ref) => ref.length > 0);
}

function collectStructuredRefs(
  provider: string | null | undefined,
  bucket: string | null | undefined,
  objectKey: string | null | undefined,
): StructuredStorageRef[] {
  const normalizedProvider = provider?.trim().toLowerCase();
  const normalizedBucket = bucket?.trim() ?? "";
  const normalizedObjectKey = objectKey?.trim() ?? "";
  if (!normalizedProvider || !normalizedBucket || !normalizedObjectKey) return [];
  if (normalizedProvider !== "supabase" && normalizedProvider !== "r2") return [];
  return [{
    provider: normalizedProvider,
    bucket: normalizedBucket,
    objectKey: normalizedObjectKey,
  }];
}

async function removeReplacedStorageRefsIfNeeded(
  admin: ReturnType<typeof serviceClient>,
  previousLegacyRefs: string[],
  previousStructuredRefs: StructuredStorageRef[],
  nextLegacyRefs: string[],
  nextStructuredRefs: StructuredStorageRef[],
) {
  const nextKeys = new Set<string>();
  for (const ref of nextLegacyRefs) {
    const parsedSupabase = parseStoragePublicURL(ref);
    if (parsedSupabase) {
      nextKeys.add(`supabase:${parsedSupabase.bucket}:${parsedSupabase.path}`);
      continue;
    }
    const parsedR2 = parseR2ObjectKeyFromPublicURL(ref);
    if (parsedR2 && R2_BUCKET) {
      nextKeys.add(`r2:${R2_BUCKET}:${parsedR2}`);
    }
  }
  for (const structured of nextStructuredRefs) {
    nextKeys.add(`${structured.provider}:${structured.bucket}:${structured.objectKey}`);
  }

  const refsToDeleteLegacy: string[] = [];
  const refsToDeleteStructured: StructuredStorageRef[] = [];

  for (const ref of previousLegacyRefs) {
    const parsedSupabase = parseStoragePublicURL(ref);
    if (parsedSupabase) {
      const key = `supabase:${parsedSupabase.bucket}:${parsedSupabase.path}`;
      if (!nextKeys.has(key)) refsToDeleteLegacy.push(ref);
      continue;
    }
    const parsedR2 = parseR2ObjectKeyFromPublicURL(ref);
    if (parsedR2 && R2_BUCKET) {
      const key = `r2:${R2_BUCKET}:${parsedR2}`;
      if (!nextKeys.has(key)) refsToDeleteLegacy.push(ref);
    }
  }

  for (const structured of previousStructuredRefs) {
    const key = `${structured.provider}:${structured.bucket}:${structured.objectKey}`;
    if (!nextKeys.has(key)) refsToDeleteStructured.push(structured);
  }

  if (refsToDeleteLegacy.length === 0 && refsToDeleteStructured.length === 0) return;
  await purgeStorageRefs(admin, refsToDeleteLegacy, refsToDeleteStructured);
}

async function purgeStorageRefs(
  admin: ReturnType<typeof serviceClient>,
  legacyRefs: Array<string | null>,
  structuredRefs: StructuredStorageRef[],
) {
  const targets = collectStorageTargets(legacyRefs, structuredRefs);
  await removeSupabaseStorageTargets(admin, targets.supabaseByBucket);
  await deleteR2Objects(Array.from(targets.r2ObjectKeys));
}

async function quarantineDeletedPostStorageRefs(
  admin: ReturnType<typeof serviceClient>,
  legacyRefs: Array<string | null>,
  structuredRefs: StructuredStorageRef[],
  context: { postID: string; authorID: string },
) {
  const targets = collectStorageTargets(legacyRefs, structuredRefs);
  await removeSupabaseStorageTargets(admin, targets.supabaseByBucket);
  await quarantineR2ObjectsForDeletedPost(Array.from(targets.r2ObjectKeys), context);
}

function collectStorageTargets(
  legacyRefs: Array<string | null>,
  structuredRefs: StructuredStorageRef[],
): { supabaseByBucket: Map<string, Set<string>>; r2ObjectKeys: Set<string> } {
  const supabaseByBucket = new Map<string, Set<string>>();
  const r2ObjectKeys = new Set<string>();

  const ingestTarget = (target: StructuredStorageRef | null) => {
    if (!target) return;
    const bucket = target.bucket.trim();
    const objectKey = target.objectKey.trim();
    if (!bucket || !objectKey) return;
    if (target.provider === "supabase") {
      const set = supabaseByBucket.get(bucket) ?? new Set<string>();
      set.add(objectKey);
      supabaseByBucket.set(bucket, set);
      return;
    }
    if (target.provider === "r2") {
      r2ObjectKeys.add(objectKey);
    }
  };

  for (const ref of legacyRefs) {
    if (!ref) continue;
    const supabaseParsed = parseStoragePublicURL(ref);
    if (supabaseParsed) {
      ingestTarget({ provider: "supabase", bucket: supabaseParsed.bucket, objectKey: supabaseParsed.path });
      continue;
    }
    const r2ObjectKey = parseR2ObjectKeyFromPublicURL(ref);
    if (r2ObjectKey && R2_BUCKET) {
      ingestTarget({ provider: "r2", bucket: R2_BUCKET, objectKey: r2ObjectKey });
    }
  }

  for (const structured of structuredRefs) {
    ingestTarget(structured);
  }

  return { supabaseByBucket, r2ObjectKeys };
}

async function removeSupabaseStorageTargets(
  admin: ReturnType<typeof serviceClient>,
  supabaseByBucket: Map<string, Set<string>>,
) {
  for (const [bucket, keys] of supabaseByBucket.entries()) {
    const objects = Array.from(keys);
    for (let i = 0; i < objects.length; i += 50) {
      await admin.storage.from(bucket).remove(objects.slice(i, i + 50));
    }
  }
}

function parseR2ObjectKeyFromPublicURL(assetRef: string): string | null {
  if (!R2_CDN_BASE_URL) return null;
  try {
    const parsed = new URL(assetRef);
    const base = new URL(R2_CDN_BASE_URL);
    if (parsed.origin !== base.origin) return null;
    const objectKey = decodeURIComponent(parsed.pathname.replace(/^\/+/, "")).trim();
    return objectKey.length > 0 ? objectKey : null;
  } catch {
    return null;
  }
}

function createR2Client(): S3Client | null {
  if (!R2_ACCOUNT_ID || !R2_ACCESS_KEY_ID || !R2_SECRET_ACCESS_KEY) {
    return null;
  }
  return new S3Client({
    region: "auto",
    endpoint: `https://${R2_ACCOUNT_ID}.r2.cloudflarestorage.com`,
    credentials: {
      accessKeyId: R2_ACCESS_KEY_ID,
      secretAccessKey: R2_SECRET_ACCESS_KEY,
    },
    forcePathStyle: true,
  });
}

async function deleteR2Objects(objectKeys: string[]): Promise<void> {
  const keys = Array.from(new Set(
    objectKeys.map((value) => value.trim()).filter((value) => value.length > 0),
  ));
  if (keys.length === 0) return;
  const client = createR2Client();
  if (!client || !R2_BUCKET) {
    console.warn("posts: r2 delete skipped because R2 credentials or bucket are missing", {
      hasClient: client !== null,
      hasBucket: Boolean(R2_BUCKET),
      attemptedKeys: keys.length,
    });
    return;
  }

  for (let i = 0; i < keys.length; i += 1000) {
    const chunk = keys.slice(i, i + 1000).map((key) => ({ Key: key }));
    try {
      await client.send(new DeleteObjectsCommand({
        Bucket: R2_BUCKET,
        Delete: {
          Objects: chunk,
          Quiet: true,
        },
      }));
    } catch (error) {
      console.warn("posts: r2 delete failed", error);
    }
  }
}

async function quarantineR2ObjectsForDeletedPost(
  objectKeys: string[],
  context: { postID: string; authorID: string },
): Promise<void> {
  const keys = Array.from(new Set(
    objectKeys
      .map((value) => normalizeR2ObjectKey(value))
      .filter((value): value is string => value !== null && !value.startsWith("deleted-posts/")),
  ));
  const client = createR2Client();
  if (!client || !R2_BUCKET) {
    console.warn("posts: r2 deleted-post quarantine skipped because R2 credentials or bucket are missing", {
      hasClient: client !== null,
      hasBucket: Boolean(R2_BUCKET),
      attemptedKeys: keys.length,
      postID: context.postID,
    });
    return;
  }

  const copiedKeys: string[] = [];
  for (const sourceKey of keys) {
    const destinationKey = deletedPostR2ObjectKey(context, sourceKey);
    try {
      await client.send(new CopyObjectCommand({
        Bucket: R2_BUCKET,
        CopySource: `${R2_BUCKET}/${encodeR2CopySourceKey(sourceKey)}`,
        Key: destinationKey,
        MetadataDirective: "COPY",
      }));
      copiedKeys.push(sourceKey);
    } catch (error) {
      console.warn("posts: r2 deleted-post quarantine copy failed", {
        postID: context.postID,
        authorID: context.authorID,
        sourceKey,
        destinationKey,
        error: error instanceof Error ? error.message : String(error),
      });
    }
  }

  if (copiedKeys.length > 0) {
    await deleteR2Objects(copiedKeys);
  }

  const manifestKey = await writeDeletedPostR2Manifest(client, context, keys, copiedKeys);

  console.log(JSON.stringify({
    event: "delete_post_r2_quarantine_complete",
    post_id: context.postID,
    author_id: context.authorID,
    attempted: keys.length,
    copied: copiedKeys.length,
    skipped_or_failed: keys.length - copiedKeys.length,
    manifest_key: manifestKey,
    prefix: `deleted-posts/${deletedPostR2PathSegment(context.authorID)}/${deletedPostR2PathSegment(context.postID)}/`,
  }));
}

async function writeDeletedPostR2Manifest(
  client: S3Client,
  context: { postID: string; authorID: string },
  attemptedKeys: string[],
  copiedKeys: string[],
): Promise<string | null> {
  const manifestKey = [
    "deleted-posts",
    deletedPostR2PathSegment(context.authorID),
    deletedPostR2PathSegment(context.postID),
    "manifest.json",
  ].join("/");
  try {
    await client.send(new PutObjectCommand({
      Bucket: R2_BUCKET,
      Key: manifestKey,
      Body: new TextEncoder().encode(JSON.stringify({
        postID: context.postID,
        authorID: context.authorID,
        deletedAt: new Date().toISOString(),
        sourceObjectKeys: attemptedKeys,
        copiedObjectKeys: copiedKeys.map((sourceKey) => deletedPostR2ObjectKey(context, sourceKey)),
        skippedOrFailedSourceObjectKeys: attemptedKeys.filter((sourceKey) => !copiedKeys.includes(sourceKey)),
      }, null, 2)),
      ContentType: "application/json",
      CacheControl: "no-store",
    }));
    return manifestKey;
  } catch (error) {
    console.warn("posts: r2 deleted-post manifest write failed", {
      postID: context.postID,
      authorID: context.authorID,
      manifestKey,
      error: error instanceof Error ? error.message : String(error),
    });
    return null;
  }
}

function deletedPostR2ObjectKey(context: { postID: string; authorID: string }, sourceKey: string): string {
  return [
    "deleted-posts",
    deletedPostR2PathSegment(context.authorID),
    deletedPostR2PathSegment(context.postID),
    sourceKey,
  ].join("/");
}

function deletedPostR2PathSegment(value: string): string {
  return value
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9._-]+/g, "-")
    .replace(/^-+|-+$/g, "") || "unknown";
}

function normalizeR2ObjectKey(value: string): string | null {
  const normalized = value.trim().replace(/^\/+/, "");
  return normalized.length > 0 ? normalized : null;
}

function encodeR2CopySourceKey(objectKey: string): string {
  return objectKey.split("/").map((part) => encodeURIComponent(part)).join("/");
}

function parseStoragePublicURL(assetRef: string): { bucket: string; path: string } | null {
  try {
    const parsed = new URL(assetRef);
    const marker = "/storage/v1/object/public/";
    const index = parsed.pathname.indexOf(marker);
    if (index == -1) return null;
    const tail = parsed.pathname.slice(index + marker.length);
    const slash = tail.indexOf("/");
    if (slash <= 0) return null;
    const bucket = tail.slice(0, slash);
    const path = tail.slice(slash + 1);
    if (!bucket || !path) return null;
    return { bucket, path };
  } catch {
    return null;
  }
}

async function postsByAuthor(url: URL, viewerIDRaw: string | null = null) {
  const authorID = String(url.searchParams.get("author_id") ?? "").trim().toLowerCase();
  if (!authorID) return badRequest("author_id required.");
  const cursor = String(url.searchParams.get("cursor") ?? "").trim() || null;
  const viewerID = String(viewerIDRaw ?? "").trim().toLowerCase();
  const isPublicRequest = !viewerID;
  const requestedLimit = Number(url.searchParams.get("limit") ?? (isPublicRequest ? "20" : "50"));
  const limit = Math.max(
    1,
    Math.min(Number.isFinite(requestedLimit) ? requestedLimit : (isPublicRequest ? 20 : 50), isPublicRequest ? 24 : 100),
  );

  const admin = serviceClient();
  const userMap = await fetchUsersByIds([authorID]);
  const author = userMap[authorID];
  if (!author) return json({ posts: [], nextCursor: null });

  if (author.isPrivate && !await canViewPrivateAuthorPosts(admin, viewerID, authorID)) {
    return json({ posts: [], nextCursor: null });
  }

  let query = admin.from("posts")
    .select(POST_LIST_COLUMNS)
    .eq("author_id", authorID)
    .is("deleted_at", null)
    .order("created_at", { ascending: false })
    .limit(limit + 1);
  if (cursor) {
    query = query.lt("created_at", cursor);
  }

  const result = await query;
  if (result.error) return badRequest(result.error.message);

  const rows = (result.data ?? []) as Record<string, unknown>[];
  const tombstonedPostIDs = await fetchDeletedPostIDSet(
    admin,
    rows.map((row) => String(row.id ?? "")),
  );
  const visibleRows = rows.filter((row) => !tombstonedPostIDs.has(String(row.id ?? "").trim().toLowerCase()));
  const pageRows = visibleRows.slice(0, limit);
  const hasMore = visibleRows.length > limit;

  let effectivePageRows = pageRows;
  const pinnedPostID = String(author.pinnedPostID ?? "").trim().toLowerCase();
  if (!cursor && pinnedPostID && !effectivePageRows.some((row) => String(row.id ?? "").trim().toLowerCase() === pinnedPostID)) {
    const pinned = await admin.from("posts")
      .select(POST_LIST_COLUMNS)
      .eq("id", pinnedPostID)
      .eq("author_id", authorID)
      .is("deleted_at", null)
      .maybeSingle();
    if (!pinned.error && pinned.data && !tombstonedPostIDs.has(pinnedPostID)) {
      effectivePageRows = [pinned.data as Record<string, unknown>, ...effectivePageRows];
    }
  }

  const mapped = effectivePageRows.map((row) => mapPost(row, author));
  const responsePosts = isPublicRequest ? mapped.map(compactPostForPublicList) : mapped;
  const nextCursor = hasMore && mapped.length > 0
    ? new Date(String(pageRows[Math.max(0, pageRows.length - 1)]?.created_at ?? mapped[mapped.length - 1].createdAt)).toISOString()
    : null;
  const deletedPostIDs = await fetchDeletedPostIDsForAuthorIDs(admin, [authorID]);

  return json({ posts: responsePosts, nextCursor, deletedPostIDs });
}

