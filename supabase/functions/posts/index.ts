  const admin = serviceClient();
  const actor = await admin.from("users").select("is_founder, is_admin").eq("id", authed).maybeSingle();
  if (actor.error) return badRequest(actor.error.message);
  const isAdmin = Boolean(actor.data?.is_founder ?? false) || Boolean(actor.data?.is_admin ?? false);
  if (!isAdmin) return unauthorized();

